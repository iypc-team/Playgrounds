//  ColorExtensions.swift

import SwiftUI
import UIKit

extension Color {
    public static var cardinalRed: Color {
        return Color(UIColor(red: 196.0/255.0, green: 30.0/255.0, blue: 58.0/255.0, alpha: 1.0))
    }
    
    public static var navyBlue: Color {
        // rgb(1,1,128)
        return Color(UIColor(red: 1.0/255.0, green: 1.0/255.0, blue: 128.0/255.0, alpha: 1.0))
    }
    
    public static var forestGreen: Color {
        // rgb(1,68,33)
        return Color(UIColor(red: 1.0/255.0, green: 68.0/255.0, blue: 33.0/255.0, alpha: 1.0))
    }
}
